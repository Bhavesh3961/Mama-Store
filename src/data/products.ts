export function isEnquiryPrice(p: Product): boolean {
  return p.price == null;
}

export function discountPercent(p: Product): number {
  if (p.mrp == null || p.price == null || p.mrp <= p.price) return 0;
  return Math.round(((p.mrp - p.price) / p.mrp) * 100);
}
